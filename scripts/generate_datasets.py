    for ticker, yr_map in STOCK_PRICES.items():
        prices_data[ticker] = {str(yr): float(yr_map[yr]) for yr in sorted(yr_map.keys()) if yr >= 1994}
        # Also ensure 1993 price exists if available for 1994 return
        if 1993 in yr_map:
            prices_data[ticker]["1993"] = float(yr_map[1993])

    # Build dividends dictionary: { ticker: { str(year): dps } }
    dividends_data = {}
    for ticker in sorted(STOCK_DIVIDENDS.keys()):
        yr_map = STOCK_DIVIDENDS[ticker]
        dividends_data[ticker] = {str(yr): float(yr_map[yr]) for yr in sorted(yr_map.keys()) if yr >= 1994}

    # Build constituents dictionary: { str(year): [ {ticker, name, market_cap_weight, trailing_1y_return, year}, ... ] }
    constituents_data = {}
    
    for year in range(1994, 2025):
        tickers = YEAR_CONSTITUENTS[year]
        weights = get_weights_for_year(year)
        
        c_list = []
        for rank, ticker in enumerate(tickers):
            weight = weights[rank]
            name = NAMES[ticker]
            
            p_curr = STOCK_PRICES[ticker][year]
            p_prev = STOCK_PRICES[ticker][year - 1]
            ret_1y = round((p_curr - p_prev) / p_prev, 4)
            
            c_list.append({
                "ticker": ticker,
                "name": name,
                "market_cap_weight": weight,
                "trailing_1y_return": ret_1y,
                "year": year,
            })
        
        constituents_data[str(year)] = c_list

    # Save to data/ directory
    data_dir = Path(__file__).resolve().parent.parent / "data"
    data_dir.mkdir(exist_ok=True)
    
    with open(data_dir / "sp500_prices.json", "w") as f:
        json.dump(prices_data, f, indent=2)

    with open(data_dir / "sp500_dividends.json", "w") as f:
        json.dump(dividends_data, f, indent=2)
        
    with open(data_dir / "sp500_constituents.json", "w") as f:
        json.dump(constituents_data, f, indent=2)
        
    print(f"Successfully wrote {data_dir / 'sp500_prices.json'}")
    print(f"Successfully wrote {data_dir / 'sp500_dividends.json'}")
    print(f"Successfully wrote {data_dir / 'sp500_constituents.json'}")

